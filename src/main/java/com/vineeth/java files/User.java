

public class User {
    private String name;
    private float balance;

    public User(String name,float balance ) {
        this.balance = balance;
        this.name = name;
    }

    public float getBalance() {
        return balance;
    }

    public void setBalance(float balance) {
        this.balance = balance;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}
